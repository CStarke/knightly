const test = require('node:test');
const assert = require('node:assert/strict');
const { createMockDal } = require('../mocks/mock-dal');
const { publishPost, syncScrapedEvents } = require('../../services/feed-service');

test('Feed & Posts BLL Invariants', async (t) => {
  await t.test('enforces server-authoritative timestamps, ignoring client clock', async () => {
    const { postsDal } = createMockDal();

    // Client attempts to spoof timestamp into the past or future
    const spoofedClientDate = '2020-01-01T00:00:00.000Z';
    const spoofedClientMs = 1577836800000;

    const post = await publishPost(
      {
        headline: 'Hackathon Kickoff',
        body: 'Join ACM this Friday in NH 276.',
        category: 'Academics',
        orgName: 'ACM',
        authorStudentId: 'student-uuid-42',
        postedAt: spoofedClientDate,
        createdAt: spoofedClientMs,
      },
      postsDal
    );

    assert.ok(post);
    assert.equal(post.author_student_id, 'student-uuid-42');
    assert.notEqual(post.posted_at, spoofedClientDate, 'Must reject client timestamp');
    assert.notEqual(post.created_at_ms, spoofedClientMs, 'Must reject client epoch ms');

    // Server timestamp should be within last 5 seconds
    const diffMs = Math.abs(Date.now() - post.created_at_ms);
    assert.ok(diffMs < 5000, `Timestamp must be freshly generated by server, diff: ${diffMs}ms`);
  });

  await t.test('strictly requires posts to be tied to a specific student for admin accountability', async () => {
    const { postsDal } = createMockDal();

    await assert.rejects(
      async () => {
        await publishPost(
          {
            headline: 'Unattributed Flyer',
            body: 'Who posted this?',
            orgName: 'ACM',
            category: 'Academics',
            // Missing authorStudentId
          },
          postsDal
        );
      },
      { message: /Author student ID is required/ }
    );
  });

  await t.test('guarantees standard 13-category taxonomy and falls back gracefully', async () => {
    const { postsDal } = createMockDal();

    // Post with invalid category "UnknownCategory" but text mentions Chapel
    const post = await publishPost(
      {
        headline: 'Morning Chapel Service',
        body: 'Join Campus Ministries in the Chapel sanctuary for worship and prayer.',
        category: 'UnknownCategory',
        orgName: 'Campus Ministries',
        authorStudentId: 'student-uuid-42',
      },
      postsDal
    );

    assert.equal(post.category, 'Faith', 'Must auto-classify into 13 taxonomy categories');
  });

  await t.test('substitutes generic line-art Drupal placeholder URLs with theme preset banners', async () => {
    const { postsDal } = createMockDal();

    const post = await publishPost(
      {
        headline: 'Arts & Music Exhibition',
        body: 'Center Art Gallery exhibition.',
        category: 'The Arts',
        orgName: 'Calvin Art',
        authorStudentId: 'student-uuid-42',
        imageUrl: 'https://calvin.edu/sites/default/files/2025-10/arts-culture.png',
      },
      postsDal
    );

    assert.equal(post.image_url, null, 'Placeholder image URL should be cleared');
    assert.equal(post.fallback_banner_svg, 'preset:amethyst:crystals');
  });

  await t.test('idempotently synchronizes scraped events using externalEventId', async () => {
    const { postsDal, state } = createMockDal();

    // Mock scraper returning 2 events
    const mockScraper = async () => [
      {
        id: 'calvin-drupal-101',
        title: 'Calvin vs Hope Basketball',
        description: 'MIAA rivalry game at Van Noord Arena.',
        category: 'Athletics',
        imageUrl: 'https://calvin.edu/sites/default/files/custom-photo.jpg',
        url: 'https://calvin.edu/events/all/101',
      },
    ];

    // First sync
    const res1 = await syncScrapedEvents({}, mockScraper, postsDal);
    assert.equal(res1.totalUpserted, 1);
    assert.equal(state.posts.length, 1);

    // Second sync with identical events
    const res2 = await syncScrapedEvents({}, mockScraper, postsDal);
    assert.equal(res2.totalUpserted, 1);
    // Still 1 post in database (deduplicated by externalEventId)
    assert.equal(state.posts.length, 1);
  });
});
