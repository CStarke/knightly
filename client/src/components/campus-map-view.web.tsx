/*Uses the same bundled map on web; no external website or PDF plugin is needed.
/ The .web.tsx filename selects this component for the web version.
/ srcDoc supplies the HTML directly instead of loading a website.
/ The sandbox allows the map's scripts without granting same-origin access.
/ @param props.html - Complete HTML generated by createCampusMapHtml.
/ @returns An embedded frame containing the map and its controls.*/

export default function CampusMapView({ html }: { html: string }) {
  return (
    <iframe
      title="Calvin University campus map"
      srcDoc={html}
      sandbox="allow-scripts"
      style={{ width: '100%', height: '100%', border: 0, flex: 1 }}
    />
  );
}